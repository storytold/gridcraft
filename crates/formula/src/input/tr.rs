/// Accepts the dotted and dotless I variants used when typing Turkish function names.
fn fold_alias(name: &str) -> String {
    name.chars()
        .flat_map(|c| match c {
            'İ' | 'ı' | 'I' => 'i'.to_lowercase(),
            _ => c.to_lowercase(),
        })
        .collect()
}

