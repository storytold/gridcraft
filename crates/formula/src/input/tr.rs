pub(crate) fn turkish_eq_ignore_case(a: &str, b: &str) -> bool {
    let mut a_chars = a.chars();
    let mut b_chars = b.chars();
    loop {
        match (a_chars.next(), b_chars.next()) {
            (None, None) => return true,
            (Some(ca), Some(cb)) => {
                if ca == cb {
                    continue;
                }
                let matches = match (ca, cb) {
                    ('i' | 'İ', 'i' | 'İ') => true,
                    ('ı' | 'I', 'ı' | 'I') => true,
                    ('ç' | 'Ç', 'ç' | 'Ç') => true,
                    ('ğ' | 'Ğ', 'ğ' | 'Ğ') => true,
                    ('ö' | 'Ö', 'ö' | 'Ö') => true,
                    ('ş' | 'Ş', 'ş' | 'Ş') => true,
                    ('ü' | 'Ü', 'ü' | 'Ü') => true,
                    (x, y) => x.eq_ignore_ascii_case(&y),
                };
                if !matches {
                    return false;
                }
            }
            _ => return false,
        }
    }
}
