#[cfg(test)]
mod tests {
    use std::collections::HashSet;

    use super::FUNCTIONS;
    use crate::FormulaLocale;

    #[test]
    fn names_are_complete_unique_and_bidirectional() {
        assert_eq!(FUNCTIONS.len(), 514);
        let mut canonical = HashSet::new();
        let mut localized = HashSet::new();
        for &(english, portuguese) in FUNCTIONS {
            assert!(canonical.insert(english), "duplicate canonical function {english}");
            assert!(localized.insert(portuguese), "duplicate Portuguese function {portuguese}");
            assert_eq!(FormulaLocale::PtBr.function_name(english), portuguese);
            assert_eq!(FormulaLocale::PtBr.canonical_name(portuguese), english);
        }
    }
}
