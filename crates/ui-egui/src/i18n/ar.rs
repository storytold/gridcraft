/// The catalog rearranged for display, built on first use so a lookup stays a linear scan like
/// the other catalogs'.
static TABLE: LazyLock<Vec<(&'static str, String)>> = LazyLock::new(|| RAW.iter().map(|(en, ar)| (*en, crate::bidi::display_rtl(ar))).collect());

pub(super) fn translate(text: &str) -> Option<&'static str> {
    TABLE.iter().find(|(en, _)| *en == text).map(|(_, ar)| ar.as_str())
}
