#[cfg(test)]
mod tests {
    use super::translate;

    #[test]
    fn context_keys_and_workbook_syntax_stay_distinct() {
        assert_eq!(translate("Orientation"), Some("Teksto kryptis"));
        assert_eq!(translate("Page Layout|Orientation"), Some("Puslapio padėtis"));
        assert_eq!(translate("Options|General"), Some("Bendrosios"));
        assert_eq!(translate("General"), Some("Bendrasis"));
        assert_eq!(translate("Sheet1!A1"), None);
        assert_eq!(translate("=SUM(1,2)"), None);
        assert_eq!(translate("A personal sheet name"), None);
    }

    #[test]
    fn neutral_counts_handle_lithuanian_number_forms() {
        for n in [0, 1, 2, 9, 10, 11, 19, 21, 22, 101, 111, 1000] {
            assert_eq!(translate("{count} cell(s) found").unwrap().replace("{count}", &n.to_string()), format!("Rasta langelių: {n}"));
            assert_eq!(translate("{n} days ago").unwrap().replace("{n}", &n.to_string()), format!("Prieš {n} d."));
            assert_eq!(translate("{n} years ago").unwrap().replace("{n}", &n.to_string()), format!("Prieš {n} m."));
        }
        assert_eq!(translate("— 1 step"), Some("— 1 veiksmas"));
        assert_eq!(translate("— {steps} steps"), Some("— Veiksmų: {steps}"));
    }

    #[test]
    fn ribbon_line_breaks_and_placeholders_survive() {
        assert_eq!(translate("Top\nAlign"), Some("Lygiuoti\nviršuje"));
        assert_eq!(translate("Bottom\nAlign"), Some("Lygiuoti\napačioje"));
        assert_eq!(translate("Page {page} of {pages}").unwrap().replace("{page}", "3").replace("{pages}", "9"), "Puslapis 3 iš 9");
        assert_eq!(translate("Find…"), Some("Rasti…"));
        assert_eq!(translate(" (password)"), Some(" (slaptažodis)"));
    }
}
