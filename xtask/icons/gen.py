#!/usr/bin/env python3
"""Regenerates crates/ui-egui/src/icons/colored.rs from xtask/icons/icons.json.

Usage: gen.py [icons.json] [colored.rs]   (defaults: next to this script, and the ui-egui crate)

icons.json is the source of GridCraft's colorized ribbon icons (original GridCraft artwork,
exported from the design's generator): `ICONS` maps a design key to its elements, each
`{f?: role, s?: role, d: svg path, w?: stroke width, dash?: "on off"}` on a 24-unit grid, and
`TABS` lists which ribbon button uses which key. Roles are colour roles resolved by the theme
(`theme::IconRole`): K ink, D dim, A accent, AS accent soft, R red, RS red soft, O amber,
OS amber soft, B blue, P paper.
"""
import json, pathlib, sys

here = pathlib.Path(__file__).resolve().parent
src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else here / "icons.json"
dst = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else here.parent.parent / "crates/ui-egui/src/icons/colored.rs"
data = json.loads(src.read_text())
ROLES = {"K": "Ink", "D": "Dim", "A": "Accent", "AS": "AccentSoft", "R": "Red", "RS": "RedSoft",
         "O": "Amber", "OS": "AmberSoft", "B": "Blue", "P": "Paper"}


def num(v):
    s = repr(float(v))
    return s


def role(r):
    if r is None:
        return "None"
    if r not in ROLES:
        raise SystemExit(f"unknown role {r}")
    return f"Some({ROLES[r]})"


def el(e):
    w = f"Some({num(e['w'])})" if "w" in e else "None"
    if "dash" in e:
        parts = e["dash"].split()
        if len(parts) != 2:
            raise SystemExit(f"unsupported dash {e['dash']}")
        dash = f"Some(({num(parts[0])}, {num(parts[1])}))"
    else:
        dash = "None"
    d = " ".join(e["d"].split())
    if '"' in d or "\\" in d:
        raise SystemExit("unexpected character in path data")
    return f'El {{ fill: {role(e.get("f"))}, stroke: {role(e.get("s"))}, width: {w}, dash: {dash}, d: "{d}" }}'


out = [
    "//! GridCraft's colorized ribbon icons: original GridCraft artwork (some shapes derive from Lucide,",
    "//! ISC; see ATTRIBUTION.md). Generated by `xtask/icons/gen.py` from `xtask/icons/icons.json`; do not",
    "//! edit by hand. Each icon is a list of elements on a 24-unit grid, painted in order: SVG path data",
    "//! with an optional fill role, an optional stroke role, a stroke width override (in grid units at",
    "//! 20 px; small icons add 0.2) and a dash pattern (`(0.01, gap)` is a row of round dots).",
    "",
    "use crate::theme::IconRole::{self, *};",
    "",
    "/// One element of a colorized icon.",
    "pub(crate) struct El {",
    "    pub fill: Option<IconRole>,",
    "    pub stroke: Option<IconRole>,",
    "    pub width: Option<f32>,",
    "    pub dash: Option<(f32, f32)>,",
    "    pub d: &'static str,",
    "}",
    "",
    "pub(crate) const ICONS: &[(&str, &[El])] = &[",
]
for key, els in data["ICONS"].items():
    out.append(f'    ("{key}", &[')
    for e in els:
        out.append(f"        {el(e)},")
    out.append("    ]),")
out.append("];")
dst.write_text("\n".join(out) + "\n")
print(f"wrote {dst} ({len(data['ICONS'])} icons)")
