#!/usr/bin/env python3
"""Regenerates crates/ui-egui/src/icons/lucide.rs from Lucide SVGs.

Usage: gen.py <dir with lucide-static icons/*.svg> <map.txt>  (map: "<Icon> <lucide-name>" per line)
Every element becomes SVG path data, so the renderer only needs a path parser.
"""
import re, sys, pathlib
src, mp = pathlib.Path(sys.argv[1]), sys.argv[2]
names = sorted({l.split()[1] for l in open(mp) if l.strip()})
def attrs(tag):
    return {k: v for k, v in re.findall(r'([\w-]+)="([^"]*)"', tag)}
def f(v):
    return float(v)
def el_to_d(name, a):
    if name == 'path':
        return a['d']
    if name == 'circle':
        cx, cy, r = f(a['cx']), f(a['cy']), f(a['r'])
        return f"M{cx-r} {cy}a{r} {r} 0 1 0 {2*r} 0a{r} {r} 0 1 0 {-2*r} 0Z"
    if name == 'ellipse':
        cx, cy, rx, ry = f(a['cx']), f(a['cy']), f(a['rx']), f(a['ry'])
        return f"M{cx-rx} {cy}a{rx} {ry} 0 1 0 {2*rx} 0a{rx} {ry} 0 1 0 {-2*rx} 0Z"
    if name == 'line':
        return f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}"
    if name in ('polyline', 'polygon'):
        pts = re.findall(r'-?[\d.]+', a['points'])
        pairs = [f"{pts[i]} {pts[i+1]}" for i in range(0, len(pts), 2)]
        return 'M' + 'L'.join(pairs) + ('Z' if name == 'polygon' else '')
    if name == 'rect':
        x, y, w, h = f(a.get('x', 0)), f(a.get('y', 0)), f(a['width']), f(a['height'])
        r = f(a.get('rx', a.get('ry', 0)))
        if r <= 0:
            return f"M{x} {y}h{w}v{h}h{-w}Z"
        return (f"M{x+r} {y}h{w-2*r}a{r} {r} 0 0 1 {r} {r}v{h-2*r}a{r} {r} 0 0 1 {-r} {r}"
                f"h{-(w-2*r)}a{r} {r} 0 0 1 {-r} {-r}v{-(h-2*r)}a{r} {r} 0 0 1 {r} {-r}Z")
    raise SystemExit(f"unsupported element {name}")
out = ["//! Lucide icons (https://lucide.dev), ISC licence: see `assets/lucide/LICENSE.txt` and ATTRIBUTION.md.",
       "//! Generated by `xtask/lucide/gen.py` from lucide-static 0.460.0; do not edit by hand.",
       "//! Each icon is a list of SVG path data on Lucide's 24×24 grid (2 px strokes, no fills).", "",
       "pub(crate) const ICONS: &[(&str, &[&str])] = &["]
for n in names:
    svg = (src / f"{n}.svg").read_text()
    ds = []
    for m in re.finditer(r'<(path|circle|ellipse|line|polyline|polygon|rect)\b([^>]*)/?>', svg):
        ds.append(el_to_d(m.group(1), attrs(m.group(2))))
    out.append(f'    ("{n}", &[' + ', '.join('"' + d + '"' for d in ds) + ']),')
out.append("];")
print("\n".join(out))
